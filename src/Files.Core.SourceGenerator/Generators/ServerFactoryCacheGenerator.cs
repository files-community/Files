namespace Files.Core.SourceGenerator.Generators;

[Generator(LanguageNames.CSharp)]
internal sealed class ServerFactoryCacheGenerator : IIncrementalGenerator
{
	private readonly record struct FactoryField(string Type, string Name);

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var fields = context.SyntaxProvider.CreateSyntaxProvider(
			static (node, _) => node is VariableDeclaratorSyntax variable &&
				variable.Identifier.ValueText.StartsWith("___objRef_global__Files_App_Server_", StringComparison.Ordinal),
			static (context, token) =>
			{
				if (context.SemanticModel.GetDeclaredSymbol(context.Node, token) is not IFieldSymbol field ||
					!field.IsStatic || field.DeclaredAccessibility != Accessibility.Private ||
					field.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString() != "WinRT.IObjectReference" ||
					field.ContainingNamespace.ToDisplayString() != "Files.App.Server")
					return (FactoryField?)null;
				return new FactoryField(field.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), field.Name);
			})
			.Where(static field => field.HasValue)
			.Select(static (field, _) => field!.Value)
			.Collect();

		context.RegisterSourceOutput(fields, static (context, fields) =>
		{
			if (fields.IsEmpty)
				return;
			var ordered = fields.Distinct().OrderBy(field => field.Type, StringComparer.Ordinal).ThenBy(field => field.Name, StringComparer.Ordinal).ToArray();
			var resets = string.Join("\n", ordered.Select((field, index) => $$"""
						global::System.Threading.Interlocked.Exchange(ref Factory{{index}}(null), null);
				"""));
			var accessors = string.Join("\n\n", ordered.Select((field, index) => $$"""
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticField, Name = "{{field.Name}}")]
					private static extern ref global::WinRT.IObjectReference? Factory{{index}}({{field.Type}}? type);
				"""));
			var source = $$"""
				// <auto-generated/>
				#nullable enable
				namespace Files.App.Helpers.Application;

				internal static class ServerFactoryCache
				{
					// Drop cached factories without disposing owners still used by in-flight calls.
					internal static void Clear()
					{
				{{resets}}
					}

				{{accessors}}
				}
				""";
			context.AddSource("ServerFactoryCache.g.cs", source);
		});
	}
}
